def get_catalog() -> dict[str, dict[str, str]]:
    if not CATALOG_FILE.exists():
        save_catalog(DEFAULT_CATALOG)
        return dict(DEFAULT_CATALOG)
    try:
        with CATALOG_FILE.open("r", encoding="utf-8") as file:
            data = json.load(file)
        if isinstance(data, dict):
            return data
    except (json.JSONDecodeError, OSError):
        pass
    return dict(DEFAULT_CATALOG)


def save_catalog(catalog: dict[str, dict[str, str]]) -> None:
    with CATALOG_FILE.open("w", encoding="utf-8") as file:
        json.dump(catalog, file, ensure_ascii=False, indent=2)


def get_all_services() -> set[str]:
    return {
        service_name
        for category in get_catalog().values()
        for service_name in category.keys()
    }


CATALOG = get_catalog()
ALL_SERVICES = get_all_services()
